// The doctor's folder: «Осмотр» — photos, questions to the patient, the protocol step by step, signing.
const { chromium } = require('playwright');
const out = process.argv[2];
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m);
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const errs = [];
  const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  p.on('pageerror', e => errs.push('pageerror: ' + (e.stack || e.message).split('\n').slice(0, 3).join(' | ')));
  p.on('requestfailed', r => errs.push('requestfailed: ' + r.url()));
  await p.addInitScript(() => { if (!sessionStorage.getItem('k')) { try { localStorage.clear(); } catch (e) {} sessionStorage.setItem('k', '1'); } });
  await p.goto('file:///home/user/whitenoise/index.html'); await p.waitForTimeout(600);
  ok((await p.$$('.home-app.folder')).length === 2, 'two folders: book and doctor');
  await p.screenshot({ path: `${out}/home.png` });
  await p.click('.home-app.doctor'); await p.waitForTimeout(350);
  ok((await p.$eval('#homeFolderName', e => e.textContent)) === 'Врач', 'doctor folder opens');
  await p.click('#homeFolderBox .home-app'); await p.waitForTimeout(700);
  ok(/Приём/.test(await p.$eval('#cardBody', e => e.textContent)), 'exam list');
  await p.screenshot({ path: `${out}/list.png` });
  await p.click('#cardBody .ca-row'); await p.waitForTimeout(400);
  ok((await p.$$('.ex-thumb')).length === 9, 'nine photos');
  ok(await p.$$eval('.ex-thumb img', is => is.every(i => i.complete && i.naturalWidth > 0)), 'photos load');
  await p.screenshot({ path: `${out}/case_top.png` });
  await p.click('.ex-thumb >> nth=2'); await p.waitForTimeout(300);
  ok(await p.isVisible('.ex-view'), 'photo viewer');
  await p.keyboard.press('ArrowRight'); await p.waitForTimeout(150);
  ok(/4 \/ 9/.test(await p.$eval('.ex-view-cap', e => e.textContent)), 'viewer flips');
  await p.screenshot({ path: `${out}/viewer.png` });
  await p.click('.ex-view-x'); await p.waitForTimeout(150);
  await p.click('.ex-asks .ca-opt:has-text("зубы мудрости")'); await p.waitForTimeout(150);
  ok(/Не знаю/.test(await p.$eval('.ex-chat', e => e.textContent)), 'patient answers');
  ok((await p.$$('.ex-step:not([hidden])')).length === 1, 'protocol shows one step at a time');
  const pickStep = async (k, v) => { await p.click(`.ex-step >> nth=${k} >> .ca-opt:has-text("${v}")`); await p.waitForTimeout(80); };
  const vals = ['Совпадает', 'Несимметричные', 'I класс', 'II класс', 'I класс', 'Не определить', 'Норма (до 1/3)', 'Норма', 'Выраженная', 'Лёгкая'];
  for (let k = 0; k < vals.length; k++) await pickStep(k, vals[k]);
  ok((await p.$$('.ex-step:not([hidden])')).length === 11, 'steps unlock in order');
  await p.click('.ex-tooth[data-n="23"]'); await p.click('.ex-chip:has-text("Вестибулярно")'); await p.click('.ex-chip:has-text("Интрузия")');
  await p.click('.ex-tooth[data-n="21"]'); await p.click('.ex-chip:has-text("Ротация")');
  await p.screenshot({ path: `${out}/teeth.png` });
  await p.click('.ex-next'); await p.waitForTimeout(150);
  await pickStep(11, 'Уточнить по ОПТГ');
  ok(await p.isVisible('.ca-sign:has-text("Подписать осмотр")'), 'sign appears after the last step');
  await p.click('.ca-sign:has-text("Подписать осмотр")'); await p.waitForTimeout(500);
  const score = await p.$eval('.ex-result .ca-score', e => e.textContent);
  ok(/Совпало с эталоном 9 из 12/.test(score), 'score: ' + score);
  ok(await p.isVisible('.ex-stamp'), 'stamp');
  ok((await p.$$('.ex-tooth.miss')).length === 1 && (await p.$$('.ex-tooth.hit')).length === 2, 'teeth chart marks missed 22');
  await p.screenshot({ path: `${out}/signed.png` });
  await p.click('#cardBack'); await p.waitForTimeout(200);
  ok(/9\/12/.test(await p.$eval('#cardBody', e => e.textContent)), 'list shows the result');
  await p.click('#homeBar'); await p.waitForTimeout(800);
  ok(await p.evaluate(() => window.__home.open()), 'back home');
  ok(/Осмотры 1\/1/.test(await p.$eval('.home-app.doctor .home-fstat', e => e.textContent)), 'doctor tile counts the exam');
  // the book folder still works
  await p.click('.home-app.folder >> nth=0'); await p.waitForTimeout(300);
  await p.click('#homeFolderBox .home-app >> nth=1'); await p.waitForTimeout(700);
  ok(/Карты пациентов/.test(await p.$eval('#cardBody', e => e.textContent)), 'card app still opens');
  await p.click('#cardBody .ca-row'); await p.waitForTimeout(200); await p.click('#cardBack'); await p.waitForTimeout(200);
  ok(/Карты пациентов/.test(await p.$eval('#cardBody', e => e.textContent)), 'card app back goes to its own list');
  console.log(errs.length ? errs.join('\n') : 'no errors');
  await b.close();
})();
